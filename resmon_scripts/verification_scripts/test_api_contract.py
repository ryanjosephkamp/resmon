def test_each_vocabulary_in_the_index_equals_its_constant():
    """The words in ``http.md`` against the objects they were read from.

    Generated and then checked, rather than generated and trusted: a value
    typed into the document by hand fails here, and so does a value added to
    the constant and not regenerated.
    """
    index = _committed(api_contract.HTTP_INDEX_PATH)
    for heading, origin, values in api_contract.vocabularies():
        line = f"**{heading}** — from {origin}. {len(values)} values:"
        assert line in index, (
            f"docs/api-contract/http.md does not carry {heading!r} as "
            f"{len(values)} values from {origin}."
        )
        rendered = "".join(f"`{value}` · " for value in values).rstrip(" ·")
        start = index.index(line)
        assert rendered in index[start:start + len(line) + len(rendered) + 8], (
            f"The {heading!r} values in docs/api-contract/http.md are not "
            f"{list(values)}."
        )


def test_the_execution_status_vocabulary_is_the_schemas():
    """Guards the parse itself, the way the renderer's vocabulary test does.

    A reformat of ``_EXECUTIONS_V19_DDL`` that made the regex miss would
    otherwise yield an empty tuple, and an empty tuple compares equal to an
    empty rendering: the document would go on saying nothing, truthfully, for
    ever.
    """
    statuses = api_contract._execution_statuses()
    assert "running" in statuses and "interrupted" in statuses
    assert len(statuses) >= 5


def test_the_guard_refusals_are_read_out_of_the_guard():
    """The four the guard can answer with — and not the route's fifth.

    ``403 signature_invalid`` belongs to ``GET /api/deliveries/{id}/bundle``,
    which checks a per-destination HMAC rather than the token. It is not a
    guard refusal and must not appear in the guard's list.
    """
    refusals = dict((reason, status) for status, reason in api_contract._guard_refusals())
    assert refusals == {
        "token_missing": 401,
        "token_invalid": 401,
        "host_refused": 403,
        "origin_refused": 403,
    }


def test_the_auth_class_comes_from_the_guards_own_constants():
    """One signed route, no exempt routes, everything else on the token."""
    from implementation_scripts import api_auth

    assert api_auth.AUTH_EXEMPT_PATHS == frozenset(), (
        "AUTH_EXEMPT_PATHS has grown. docs/api-contract/http.md says it is empty."
    )
    classes: dict[str, list[str]] = {}
    for _method, path in api_contract.route_keys():
        classes.setdefault(api_contract.auth_class(path), []).append(path)
    assert sorted(set(classes.get("signed link", []))) == [
        "/api/deliveries/{delivery_id}/bundle"
    ]
    assert "exempt" not in classes
    assert len(set(classes["token"])) == len(
        {path for _m, path in api_contract.route_keys()}
    ) - 1


