def test_two_generations_are_byte_identical():
    """The same process, twice. Sorted keys are what make this true.

    CI runs this file on Python 3.10, 3.11 and 3.12, which is the part of P4
    this cannot reach from one interpreter: three versions agreeing on the
    committed bytes is three green columns, not an assertion here.
    """
    assert api_contract.contract_json() == api_contract.contract_json()
    assert api_contract.render_http_md() == api_contract.render_http_md()


def test_sse_routes_are_the_three_that_stream():
    """Named, because "does this stream" is the question a client gets wrong.

    A client that fetches one of these and waits for a JSON body waits for
    ever. There is no declared response type to read, so the generator looks
    for the media type in the handler's own source; this pins what it found, so
    a fourth streaming route arrives as a red test rather than as a hang.
    """
    streaming = sorted(
        f"{sorted(route.methods)[0]} {route.path}"
        for route in api_contract.api_routes()
        if api_contract.streams_sse(route)
    )
    assert streaming == [
        "GET /api/evidence/projects/{project_id}/answers/{answer_id}/events",
        "GET /api/executions/{exec_id}/progress/stream",
        "POST /api/assistant/sessions/{session_id}/messages",
    ]
