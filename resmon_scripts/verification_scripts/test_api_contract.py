def test_committed_index_is_a_fresh_generation():
    """``http.md`` byte for byte, including the tables and the counts."""
    assert _committed(api_contract.HTTP_INDEX_PATH) == api_contract.render_http_md(), (
        "docs/api-contract/http.md is not what the generator produces. Regenerate "
        f"with `{api_contract.REGENERATE_COMMAND}` — never edit it by hand."
    )


def test_every_route_is_mapped_to_a_register_row():
    """184 of 184. A new route is red until somebody says what it serves.

    The point of the index is that a renderer rebuild can ask "which screens
    does this route belong to" and get an answer for every route. One route
    with no answer makes that false for the whole file, so an unmapped route
    fails here rather than quietly rendering as absent.
    """
    unmapped = [
        f"{method} {path}"
        for method, path in api_contract.route_keys()
        if (method, path) not in api_contract.ROUTE_JOURNEYS
    ]
    assert not unmapped, (
        "Routes with no row in api_contract.ROUTE_JOURNEYS:\n  "
        + "\n  ".join(sorted(unmapped))
        + "\nAdd each one to the mapping with the register row (J01…J44) it serves."
    )


def test_the_mapping_has_no_route_the_app_does_not():
    """The other direction: a mapping entry for a route that has gone."""
    actual = set(api_contract.route_keys())
    stale = [f"{m} {p}" for m, p in api_contract.ROUTE_JOURNEYS if (m, p) not in actual]
    assert not stale, (
        "api_contract.ROUTE_JOURNEYS maps routes the app no longer has:\n  "
        + "\n  ".join(sorted(stale))
    )


def test_every_register_id_used_is_one_of_the_forty_four():
    """``J45`` and ``J7`` are both typos, and both would render as a lost row."""
    assert len(api_contract.REGISTER) == 44
    known = set(api_contract.REGISTER_TITLES)
    used = {
        journey
        for journeys in api_contract.ROUTE_JOURNEYS.values()
        for journey in journeys
    }
    assert used <= known, (
        "Register ids used by the mapping that are not in the register: "
        + ", ".join(sorted(used - known))
    )
    assert set(api_contract.ROWLESS_REASONS) <= known


def test_every_register_row_appears_in_the_index():
    """All 44 headings, in order, whether or not they carry a route."""
    index = _committed(api_contract.HTTP_INDEX_PATH)
    position = -1
    for jid, title in api_contract.REGISTER:
        heading = f"## {jid} — {title}"
        found = index.find(heading)
        assert found > -1, f"{heading!r} is not in docs/api-contract/http.md"
        assert found > position, f"{jid} is out of order in docs/api-contract/http.md"
        position = found


def test_a_row_with_no_route_says_so():
    """An empty table and an unwritten one look identical; neither is allowed."""
    rows_with_routes = {
        journey
        for journeys in api_contract.ROUTE_JOURNEYS.values()
        for journey in journeys
    }
    mcp_keys, _ = api_contract.mcp_driven_routes()
    if mcp_keys:
        rows_with_routes.add("J44")
    rowless = {jid for jid, _ in api_contract.REGISTER} - rows_with_routes
    assert rowless == set(api_contract.ROWLESS_REASONS), (
        "The rows with no route and the rows with a written reason have come apart. "
        f"No route: {sorted(rowless)}; reason written: "
        f"{sorted(api_contract.ROWLESS_REASONS)}."
    )


