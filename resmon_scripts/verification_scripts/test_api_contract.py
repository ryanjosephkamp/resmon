# resmon_scripts/verification_scripts/test_api_contract.py
"""The HTTP surface against the committed contract.

``docs/api-contract/openapi.json`` and ``docs/api-contract/http.md`` describe
every route the renderer, the MCP server and the assistant use. They are
generated by ``implementation_scripts/api_contract.py`` from the real FastAPI
application, and this file regenerates them in-process and fails on any
difference.

**A contract change takes its own pull request.** That is what these tests are
for. When one of them goes red the answer is never to edit the committed file
by hand: run

    python -m implementation_scripts.api_contract --write

from ``resmon_scripts/``, look at the diff, and if the surface really did
change, open a pull request whose body says which routes changed and why. The
renderer is rebuilt against this file; a screen may call what is in it and
nothing else, so a silent change here is a change nobody downstream can see
coming.

The failures below are deliberately per-route. One assertion over a 130 KB
document tells you that something moved and leaves you to find it; naming the
routes that were added, removed or reshaped is the difference between a red
test you can act on and one you re-run hoping.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "resmon_scripts"))

from implementation_scripts import api_contract  # noqa: E402


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

#: The methods an operation may appear under in an OpenAPI path item.
_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")

#: The parts of an operation that are prose rather than shape. A change to one
#: of these is still a change to the committed file — the guard goes red either
#: way — but the failure says which kind it is, because "somebody improved a
#: docstring" and "the request body lost a field" want different reviewers.
_PROSE_KEYS = frozenset({"description", "summary"})


def _operations(document: dict) -> dict[tuple[str, str], dict]:
    """``(METHOD, path)`` -> operation, for every operation in the document."""
    out: dict[tuple[str, str], dict] = {}
    for path, item in (document.get("paths") or {}).items():
        for method in _METHODS:
            if method in item:
                out[(method.upper(), path)] = item[method]
    return out


def _shape(operation: dict) -> dict:
    """The operation with its prose taken out."""
    return {k: v for k, v in operation.items() if k not in _PROSE_KEYS}


def _committed(path: Path) -> str:
    if not path.exists():  # pragma: no cover — only on a broken checkout
        pytest.fail(
            f"{path.relative_to(PROJECT_ROOT)} is missing. Generate it with "
            f"`{api_contract.REGENERATE_COMMAND}` from resmon_scripts/."
        )
    return path.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def fresh_openapi() -> dict:
    return api_contract.normalised_openapi()


@pytest.fixture(scope="module")
def committed_openapi() -> dict:
    return json.loads(_committed(api_contract.OPENAPI_PATH))


# ---------------------------------------------------------------------------
# The document itself
# ---------------------------------------------------------------------------

def test_committed_openapi_describes_the_routes_the_app_has(
    fresh_openapi, committed_openapi
):
    """Every route in the app is in the contract, and nothing else is.

    The first of the per-route checks and the one that catches a route added or
    deleted. It runs before the shape comparison on purpose: a route that is
    simply absent explains every downstream difference, and reporting both at
    once buries it.
    """
    fresh = set(_operations(fresh_openapi))
    committed = set(_operations(committed_openapi))
    added = sorted(f"{m} {p}" for m, p in fresh - committed)
    removed = sorted(f"{m} {p}" for m, p in committed - fresh)
    assert not (added or removed), (
        "The app's routes and docs/api-contract/openapi.json disagree.\n"
        + ("".join(f"  added, not in the contract: {r}\n" for r in added))
        + ("".join(f"  in the contract, no longer a route: {r}\n" for r in removed))
        + f"A contract change takes its own PR. Regenerate with "
          f"`{api_contract.REGENERATE_COMMAND}` and say in the PR body what changed."
    )


def test_every_route_keeps_the_shape_the_contract_gives_it(
    fresh_openapi, committed_openapi
):
    """Parameters, request bodies and responses, one route at a time."""
    fresh = _operations(fresh_openapi)
    committed = _operations(committed_openapi)
    differences = []
    for key in sorted(fresh.keys() & committed.keys()):
        if _shape(fresh[key]) != _shape(committed[key]):
            differences.append(f"  {key[0]} {key[1]}: request or response shape")
        elif fresh[key] != committed[key]:
            differences.append(f"  {key[0]} {key[1]}: summary or description only")
    assert not differences, (
        "Routes whose description in docs/api-contract/openapi.json is out of date:\n"
        + "\n".join(differences)
        + f"\nRegenerate with `{api_contract.REGENERATE_COMMAND}`. A line reading "
          "'summary or description only' is a docstring edit and not a change to the "
          "seam; anything else is, and the PR body says what moved and why."
    )


def test_the_shared_schemas_match(fresh_openapi, committed_openapi):
    """``components.schemas`` — the request models — one model at a time."""
    fresh = (fresh_openapi.get("components") or {}).get("schemas") or {}
    committed = (committed_openapi.get("components") or {}).get("schemas") or {}
    added = sorted(set(fresh) - set(committed))
    removed = sorted(set(committed) - set(fresh))
    changed = sorted(
        name for name in set(fresh) & set(committed) if fresh[name] != committed[name]
    )
    assert not (added or removed or changed), (
        "docs/api-contract/openapi.json disagrees with the app's models.\n"
        + "".join(f"  new model: {n}\n" for n in added)
        + "".join(f"  model gone: {n}\n" for n in removed)
        + "".join(f"  model changed: {n}\n" for n in changed)
        + f"Regenerate with `{api_contract.REGENERATE_COMMAND}`."
    )


def test_committed_openapi_is_byte_for_byte_a_fresh_generation():
    """The last word, after the readable per-route failures above.

    Those name what changed; this one is what makes the file *the* contract
    rather than an approximation of it — whitespace, key order and the trailing
    newline included.
    """
    assert _committed(api_contract.OPENAPI_PATH) == api_contract.contract_json(), (
        "docs/api-contract/openapi.json is not what the app generates. "
        f"Regenerate with `{api_contract.REGENERATE_COMMAND}`."
    )


def test_the_contract_carries_no_app_version(committed_openapi):
    """``info.version`` is removed, so a release does not move the contract."""
    assert "version" not in (committed_openapi.get("info") or {}), (
        "info.version is back in the contract. It is the app version, it moves at "
        "every release, and a contract that changes then says nothing about whether "
        "the surface changed."
    )


def test_no_route_declares_a_response_model():
    """0 of 184 — and the index says so rather than inventing schemas.

    This is not a rule about how routes should be written; it is the fact the
    index is honest about. If a route ever does declare one, this test is the
    prompt to say so in ``http.md`` instead of leaving the reader with a claim
    that has quietly stopped being true.
    """
    routes = api_contract.api_routes()
    declared = sorted(
        f"{sorted(r.methods)[0]} {r.path}" for r in routes if r.response_model is not None
    )
    assert not declared, (
        "These routes now declare a response_model, so docs/api-contract/http.md's "
        "'not one of the routes declares a response_model' is no longer true:\n  "
        + "\n  ".join(declared)
    )


